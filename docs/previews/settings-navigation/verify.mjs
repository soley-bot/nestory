import { chromium } from "playwright";
import AxeBuilder from "@axe-core/playwright";
import { mkdir, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
const output = "output/playwright/settings";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const evidence = [];
try {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
    const context = await browser.newContext({ viewport });
    await context.route("**/*", (route) => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
    const page = await context.newPage(); const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("http://127.0.0.1:4329/people");
    await page.getByRole("link", { name: "Return to Organization" }).click();
    await page.getByRole("textbox", { name: "Workspace name" }).waitFor();
    const size = viewport.width === 390 ? "mobile" : "desktop";
    assert.equal(await page.getByRole("navigation", { name: "Settings sections" }).getByRole("link").count(), 6);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    if (size === "mobile") for (const link of await page.getByRole("navigation", { name: "Settings sections" }).getByRole("link").all()) assert.ok((await link.boundingBox()).height >= 44);
    await page.screenshot({ path: `${output}/${size}.png`, fullPage: true });
    await page.getByRole("textbox", { name: "Workspace name" }).fill("Unsaved sample name");
    await page.getByRole("link", { name: "Branches 1", exact: false }).last().click();
    const dialog = page.getByRole("dialog", { name: "Open Branches?" });
    await dialog.waitFor();
    await page.screenshot({ path: `${output}/${size}-draft.png`, fullPage: true });
    assert.deepEqual((await new AxeBuilder({ page }).include('[role="dialog"]').analyze()).violations, []);
    await page.keyboard.press("Escape");
    assert.equal(await page.getByRole("textbox", { name: "Workspace name" }).inputValue(), "Unsaved sample name");
    const refreshDialogPromise = page.waitForEvent("dialog");
    const refresh = page.reload({ timeout: 3000 }).catch(() => null);
    const refreshDialog = await refreshDialogPromise;
    assert.equal(refreshDialog.type(), "beforeunload");
    await refreshDialog.dismiss();
    await refresh;
    assert.equal(await page.getByRole("textbox", { name: "Workspace name" }).inputValue(), "Unsaved sample name");
    const entries = await page.evaluate(() => navigation.entries().map((entry) => entry.key));
    await page.evaluate(() => history.back());
    await page.getByRole("dialog", { name: "Open this page?" }).waitFor();
    assert.equal(new URL(page.url()).pathname, "/settings/organization");
    assert.deepEqual(await page.evaluate(() => navigation.entries().map((entry) => entry.key)), entries);
    await page.getByRole("button", { name: "Keep editing" }).click();
    assert.equal(await page.getByRole("textbox", { name: "Workspace name" }).inputValue(), "Unsaved sample name");
    await page.evaluate(() => history.back());
    await page.getByRole("button", { name: "Discard and open this page" }).click();
    await page.getByRole("heading", { name: "Synthetic navigation destination" }).waitFor();
    assert.equal(new URL(page.url()).pathname, "/people");
    assert.deepEqual(await page.evaluate(() => navigation.entries().map((entry) => entry.key)), entries);
    await page.evaluate(() => history.forward());
    await page.getByRole("textbox", { name: "Workspace name" }).waitFor();
    await page.getByRole("textbox", { name: "Workspace name" }).fill("Synthetic fail name");
    await page.getByRole("button", { name: "Save changes" }).click();
    await page.getByText("Synthetic save failed. Try again.").waitFor();
    await page.getByRole("textbox", { name: "Workspace name" }).fill("Saved sample name");
    await page.getByRole("button", { name: "Save changes" }).click();
    await page.getByRole("status").filter({ hasText: "Changes saved" }).waitFor();
    assert.deepEqual(errors, []);
    evidence.push({ viewport, navigationLinks: 6, noOverflow: true, contextLinkCancel: true, refreshCancelRetainsDraft: true, nativeBackCancelAndConfirm: true, originalHistoryRetained: true, forward: true, saveErrorAndRetry: true, dialogAxeViolations: 0, pageErrors: errors });
    await context.close();
  }
  await writeFile(`${output}/browser-evidence.json`, JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify(evidence));
} finally { await browser.close(); }
